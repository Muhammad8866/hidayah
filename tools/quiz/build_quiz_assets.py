"""Builds the offline data files the Islamic quiz generates questions from.

  app/src/main/assets/quiz/quran-simple.txt   Tanzil Quran text, copied verbatim (CC BY 3.0).
  app/src/main/assets/quiz/hadith-sayings.tsv Prophetic sayings (Arabic matn only) extracted from
                                              Sahih al-Bukhari and Sahih Muslim.

Hadith are kept in the original Arabic only - no translation - so no translator's wording or
interpolation reaches the app. Source: github.com/fawazahmed0/hadith-api (public domain).

Run from the repo root:  python tools/quiz/build_quiz_assets.py
"""
import json
import os
import re
import unicodedata
import urllib.request

OUT = os.path.join('app', 'src', 'main', 'assets', 'quiz')
TANZIL_URL = ('https://tanzil.net/pub/download/index.php?quranType=simple&outType=txt-2&agree=true'
              '&marks=true&sajdah=true&tatweel=true')
HADITH_URL = 'https://cdn.jsdelivr.net/gh/fawazahmed0/hadith-api@1/editions/{}.min.json'

MIN_WORDS, MAX_WORDS = 8, 45
# A saying is the quoted speech right after the salawat that follows the Prophet's name.
SAYING = re.compile(r'صلى الله عليه وسلم[^"]{0,40}?"\s*([^"]+?)\s*"')


def fetch(url):
    with urllib.request.urlopen(url, timeout=180) as r:
        return r.read()


def normalize(text):
    """Letters only, for de-duplication: drops harakat, tatweel and punctuation."""
    text = ''.join(c for c in unicodedata.normalize('NFKD', text) if unicodedata.category(c) != 'Mn')
    text = text.replace('ـ', '')
    text = re.sub('[إأآٱ]', 'ا', text).replace('ى', 'ي').replace('ة', 'ه')
    return ' '.join(re.sub(r'[^ء-ي ]', ' ', text).split())


def sayings(edition, citation):
    data = json.loads(fetch(HADITH_URL.format(edition)))
    for h in data['hadiths']:
        number = citation(h)
        if not number:
            continue
        m = SAYING.search(h['text'].replace('‏', ''))
        if not m:
            continue
        saying = ' '.join(m.group(1).split())
        if MIN_WORDS <= len(saying.split()) <= MAX_WORDS and '\t' not in saying:
            yield number, h['reference']['book'], saying


def bukhari_number(h):
    return str(h['hadithnumber'])


def muslim_number(h):
    # Cite the standard (Fuad Abd al-Baqi) number, e.g. 131.02 -> "131".
    n = h.get('arabicnumber')
    return str(int(float(n))) if n else None


def main():
    os.makedirs(OUT, exist_ok=True)
    quran = fetch(TANZIL_URL)
    assert b'Tanzil Project' in quran
    with open(os.path.join(OUT, 'quran-simple.txt'), 'wb') as f:
        f.write(quran)

    seen, rows = set(), []
    for collection, edition, citation in (('bukhari', 'ara-bukhari', bukhari_number),
                                          ('muslim', 'ara-muslim', muslim_number)):
        for number, book, saying in sayings(edition, citation):
            key = normalize(saying)
            if key in seen:
                continue  # Repeated or agreed-upon (muttafaq alayh) wording: keep the first.
            seen.add(key)
            rows.append(f'{collection}\t{number}\t{book}\t{saying}')

    header = [
        '# Prophetic sayings (Arabic matn) from Sahih al-Bukhari and Sahih Muslim.',
        '# Source: github.com/fawazahmed0/hadith-api (public domain). Generated by tools/quiz/build_quiz_assets.py',
        '# collection<TAB>hadith number<TAB>book (kitab) number<TAB>saying',
    ]
    with open(os.path.join(OUT, 'hadith-sayings.tsv'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(header + rows) + '\n')
    print(f'quran-simple.txt: {len(quran)} bytes, hadith-sayings.tsv: {len(rows)} sayings')


if __name__ == '__main__':
    main()
